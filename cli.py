#!/usr/bin/env python3
"""
CLI Tool for CIDOO ABM066 Keyboard LCD (macOS).
Supports checking status, synchronizing clock, and uploading images/GIFs.
"""

import sys
import os
import argparse
import subprocess
import shutil
import time
from typing import List, Tuple

from cidoo_driver import CidooABM066, rgba_pixels_to_rgb565, from_bcd


def cmd_status(args):
    print("Connecting to CIDOO ABM066...")
    dev = CidooABM066()
    if not dev.find_and_open():
        print("Error: CIDOO ABM066 keyboard not found.")
        print("Please check that the keyboard is plugged in via USB.")
        sys.exit(1)

    try:
        cfg = dev.read_config(0)
        slot = cfg[33]
        frames = cfg[34]
        interval = cfg[46]
        time_str = "20{:02d}-{:02d}-{:02d} {:02d}:{:02d}:{:02d}".format(
            from_bcd(cfg[41]), from_bcd(cfg[40]), from_bcd(cfg[39]),
            from_bcd(cfg[37]), from_bcd(cfg[36]), from_bcd(cfg[35])
        )
        print("==========================================")
        print(" Keyboard: CIDOO ABM066 LCD Screen")
        print(f" Status:   Connected (USB HID)")
        print(f" Active:   Slot {slot}")
        print(f" Frames:   {frames}")
        print(f" Interval: {interval} ms")
        print(f" LCD Time: {time_str}")
        print("==========================================")
    finally:
        dev.close()


def cmd_sync_time(args):
    slot = getattr(args, 'slot', 1)
    print(f"Synchronizing clock on Slot {slot} to Mac local time...")
    dev = CidooABM066()
    if not dev.find_and_open():
        print("Error: CIDOO ABM066 keyboard not found.")
        sys.exit(1)

    try:
        now = dev.sync_time(slot - 1)
        print(f"Success! LCD clock synchronized to: {now.strftime('%Y-%m-%d %H:%M:%S')}")
    finally:
        dev.close()


def convert_image_magick(filepath: str, fit: str = 'cover', max_frames: int = 100, rotate: int = 0) -> Tuple[List[bytes], int]:
    """Convert image or GIF into 96x160 RGB565 frames using ImageMagick."""
    if not shutil.which('magick'):
        return None, 40

    # Determine frame delay if GIF
    delay_ms = 40
    try:
        res = subprocess.run(['magick', 'identify', '-format', '%T\n', filepath],
                             capture_output=True, text=True, check=True)
        ticks = [int(line.strip()) for line in res.stdout.strip().split('\n') if line.strip().isdigit()]
        if ticks:
            # Magick %T is 1/100s, convert to ms
            avg_ticks = sum(ticks) / len(ticks)
            delay_ms = max(20, min(500, int(avg_ticks * 10)))
    except Exception:
        pass

    # Build resize arguments based on fit mode (screen resolution: 96x160)
    rot_args = ['-rotate', str(rotate)] if rotate in (90, 180, 270) else []
    if fit == 'cover':
        resize_args = rot_args + ['-resize', '96x160^', '-gravity', 'center', '-extent', '96x160']
    elif fit == 'contain':
        resize_args = rot_args + ['-resize', '96x160', '-background', 'black', '-gravity', 'center', '-extent', '96x160']
    else:  # stretch
        resize_args = rot_args + ['-resize', '96x160!']

    cmd = ['magick', filepath, '-coalesce'] + resize_args + ['-depth', '8', 'rgba:-']
    res = subprocess.run(cmd, capture_output=True, check=True)
    raw_rgba = res.stdout

    bytes_per_frame = 96 * 160 * 4  # 61,440 bytes
    total_frames = len(raw_rgba) // bytes_per_frame
    if total_frames == 0:
        raise ValueError(f"No frames could be extracted from {filepath}")

    if total_frames > max_frames:
        print(f"Limiting GIF from {total_frames} frames to {max_frames} frames.")
        total_frames = max_frames

    rgb565_frames = []
    for i in range(total_frames):
        chunk = raw_rgba[i * bytes_per_frame : (i + 1) * bytes_per_frame]
        rgb565 = rgba_pixels_to_rgb565(chunk, 96, 160)
        rgb565_frames.append(rgb565)

    return rgb565_frames, delay_ms


def convert_image_sips(filepath: str, rotate: int = 0) -> List[bytes]:
    """Fallback static image converter using macOS built-in sips tool (96x160)."""
    import tempfile
    with tempfile.NamedTemporaryFile(suffix='.bmp', delete=False) as tmp:
        tmp_bmp = tmp.name

    try:
        # Resize to 96x160 (sips takes height width)
        sips_cmd = ['/usr/bin/sips']
        if rotate in (90, 180, 270):
            sips_cmd += ['-r', str(rotate)]
        sips_cmd += ['-z', '160', '96', '-s', 'format', 'bmp', filepath, '--out', tmp_bmp]
        subprocess.run(sips_cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with open(tmp_bmp, 'rb') as f:
            bmp_data = f.read()

        # Parse BMP header
        if bmp_data[:2] != b'BM':
            raise ValueError("Invalid BMP generated by sips")
        pixel_offset = int.from_bytes(bmp_data[10:14], 'little')
        bpp = int.from_bytes(bmp_data[28:30], 'little')
        width = int.from_bytes(bmp_data[18:22], 'little')
        height = int.from_bytes(bmp_data[22:26], 'little', signed=True)

        is_top_down = (height < 0)
        h = abs(height)
        w = width

        row_stride = ((w * (bpp // 8) + 3) // 4) * 4
        rgb565_out = bytearray(w * h * 2)

        for y in range(h):
            src_y = y if is_top_down else (h - 1 - y)
            row_start = pixel_offset + src_y * row_stride
            for x in range(w):
                px_start = row_start + x * (bpp // 8)
                b = bmp_data[px_start]
                g = bmp_data[px_start + 1]
                r = bmp_data[px_start + 2]
                val = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                dst_idx = (x * h + y) * 2
                rgb565_out[dst_idx] = (val >> 8) & 0xFF
                rgb565_out[dst_idx + 1] = val & 0xFF

        return [bytes(rgb565_out)]
    finally:
        if os.path.exists(tmp_bmp):
            os.remove(tmp_bmp)


def cmd_upload(args):
    filepath = args.file
    if not os.path.isfile(filepath):
        print(f"Error: File not found: {filepath}")
        sys.exit(1)

    rotate = getattr(args, 'rotate', 0)
    print(f"Processing '{filepath}' (target 96x160, rotate {rotate}°)...")
    frames, detected_interval = convert_image_magick(filepath, fit=args.fit, max_frames=args.max_frames, rotate=rotate)
    if not frames:
        print("ImageMagick not found, falling back to macOS sips (static images only)...")
        frames = convert_image_sips(filepath, rotate=rotate)
        detected_interval = 40

    interval = args.interval if args.interval is not None else detected_interval
    slot = args.slot

    print(f"Extracted {len(frames)} frame(s) (96x160 RGB565).")
    print(f"Target: Slot {slot}, Interval: {interval}ms")

    dev = CidooABM066()
    if not dev.find_and_open():
        print("Error: CIDOO ABM066 keyboard not found.")
        sys.exit(1)

    last_pct = -1

    def progress_callback(sent, total, msg):
        nonlocal last_pct
        pct = (sent * 100) // total if total > 0 else 0
        if pct != last_pct:
            last_pct = pct
            bar_len = 30
            filled = int(bar_len * pct / 100)
            bar = '=' * filled + '-' * (bar_len - filled)
            sys.stdout.write(f"\r[{bar}] {pct:3d}% | {msg[:40]:<40}")
            sys.stdout.flush()

    try:
        print("Starting upload to keyboard flash...")
        dev.upload_frames(frames, slot=slot, interval_ms=interval, progress_cb=progress_callback)
        sys.stdout.write("\n")
        print("==========================================")
        print(" SUCCESS! Image/GIF uploaded to CIDOO LCD.")
        print(f" Active Slot: {slot}")
        print(f" Frame Count: {len(frames)}")
        print(f" Frame Delay: {interval} ms")
        print("==========================================")
    except Exception as e:
        sys.stdout.write("\n")
        print(f"\nUpload failed: {e}")
        sys.exit(1)
    finally:
        dev.close()


def main():
    parser = argparse.ArgumentParser(description="CIDOO ABM066 LCD Custom Tool (macOS CLI)")
    subparsers = parser.add_subparsers(dest='command', help='Sub-commands')

    # status
    p_status = subparsers.add_parser('status', help='Check connection and read LCD settings')
    p_status.set_defaults(func=cmd_status)

    # sync-time
    p_sync = subparsers.add_parser('sync-time', help='Synchronize keyboard clock to Mac local time')
    p_sync.add_argument('--slot', type=int, choices=[1, 2], default=1, help='Configuration slot (1 or 2, default: 1)')
    p_sync.set_defaults(func=cmd_sync_time)

    # upload
    p_upload = subparsers.add_parser('upload', help='Upload image or animated GIF to keyboard LCD')
    p_upload.add_argument('file', help='Path to image or GIF file')
    p_upload.add_argument('--slot', type=int, choices=[1, 2], default=1, help='Custom slot (1 or 2, default: 1)')
    p_upload.add_argument('--interval', type=int, default=None, help='Animation speed in ms (e.g. 25, 40, 50, 100)')
    p_upload.add_argument('--fit', choices=['cover', 'contain', 'stretch'], default='cover',
                          help='Aspect ratio scaling mode (default: cover)')
    p_upload.add_argument('--rotate', type=int, choices=[0, 90, 180, 270], default=0,
                          help='Rotate image clockwise in degrees (0, 90, 180, 270, default: 0)')
    p_upload.add_argument('--max-frames', type=int, default=80, help='Maximum frames to upload (default: 80)')
    p_upload.set_defaults(func=cmd_upload)

    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        sys.exit(0)

    args.func(args)


if __name__ == '__main__':
    main()
